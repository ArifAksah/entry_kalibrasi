INSERT INTO public.order_item_document_assignment_conflicts (
  calibration_order_item_id, certificate_assignment, letter_assignment
)
SELECT c.calibration_order_item_id,
  jsonb_build_object('verifikator_1',c.verifikator_1,'verifikator_2',c.verifikator_2,'verifikator_3',c.verifikator_3,'authorized_by',c.authorized_by),
  jsonb_build_object('verifikator_1',l.verifikator_1,'verifikator_2',l.verifikator_2,'verifikator_3',l.verifikator_3,'authorized_by',l.authorized_by)
FROM public.certificate c JOIN public.letter l USING (calibration_order_item_id)
WHERE ROW(c.verifikator_1,c.verifikator_2,c.verifikator_3,c.authorized_by)
  IS DISTINCT FROM ROW(l.verifikator_1,l.verifikator_2,l.verifikator_3,l.authorized_by)
ON CONFLICT (calibration_order_item_id) DO NOTHING;

INSERT INTO public.order_item_document_assignments (
  calibration_order_item_id, verifikator_1, verifikator_2, verifikator_3, authorized_by
)
SELECT i.id,
  COALESCE(c.verifikator_1, l.verifikator_1),
  COALESCE(c.verifikator_2, l.verifikator_2),
  COALESCE(c.verifikator_3, l.verifikator_3),
  COALESCE(c.authorized_by, l.authorized_by)
FROM public.calibration_order_items i
LEFT JOIN public.certificate c ON c.calibration_order_item_id = i.id
LEFT JOIN public.letter l ON l.calibration_order_item_id = i.id
WHERE c.id IS NOT NULL OR l.id IS NOT NULL
ON CONFLICT (calibration_order_item_id) DO NOTHING;

INSERT INTO public.order_item_document_checkers (assignment_id, personel_id, sort_order)
SELECT a.id, team.personel_id, row_number() OVER (PARTITION BY a.id ORDER BY team.priority, team.personel_id) - 1
FROM public.order_item_document_assignments a
JOIN public.calibration_order_items i ON i.id = a.calibration_order_item_id
JOIN LATERAL (
  SELECT o.created_by AS personel_id, 0 AS priority FROM public.calibration_orders o
  WHERE o.id = i.order_id AND o.created_by IS NOT NULL
  UNION
  SELECT cop.personel_id, 1 FROM public.calibration_order_personnel cop WHERE cop.order_id = i.order_id
) team ON true
WHERE NOT EXISTS (SELECT 1 FROM public.order_item_document_checkers c WHERE c.assignment_id = a.id)
ON CONFLICT DO NOTHING;

